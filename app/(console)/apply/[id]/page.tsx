"use client";
import Link from "next/link";
import { useParams } from "next/navigation";
import Shell from "@/components/Shell";
import { Head, Panel, Tag, fmtDate } from "@/components/ui";
import { useStore } from "@/lib/store";
import { useT } from "@/lib/i18n";
import { FIRMS, facility, test } from "@/lib/data/catalog";
import { evaluate } from "@/lib/core/eligibility";
import { firmType, schemeName, statusName, testName } from "@/components/reasons";

export default function Pack() {
  const { id } = useParams<{ id: string }>();
  const s = useStore();
  const t = useT();
  const a = s.applications.find((x) => x.id === id);
  if (!a) return <Shell crumbs={["Application"]}><div className="empty">{t("Application not found.")}</div></Shell>;
  const p = s.products.find((x) => x.id === a.productId)!;
  const f = facility(a.facilityId)!;
  const firm = FIRMS.find((x) => x.id === p.firmId)!;
  const r = evaluate(p, f, a.tests);
  const P = (params: Record<string, string | number>) => ({ ...params, scheme: params.scheme ? t(String(params.scheme)) : "" });
  return (
    <Shell crumbs={["Applications", a.id]}>
      <Head eyebrow={t("Application pack")} title={<span className="mono">{a.id}</span>} sub={`${p.name} → ${t(f.name)}`}
        right={<div className="row noprint"><Tag tone={a.status === "approved" ? "i" : "a"}>{statusName(t, a.status)}</Tag><button className="btn" onClick={() => print()}>{t("Print or save PDF")}</button><Link className="btn g" href="/apply">{t("Back")}</Link></div>} />
      <div className="grid g2">
        <Panel title={`1 · ${t("Applicant")}`}>
          <div className="pb"><dl className="kv">
            <dt>{t("Firm")}</dt><dd>{firm.name}</dd><dt>{t("Type")}</dt><dd>{firmType(t, firm.type)}</dd><dt>{t("City")}</dt><dd>{t(firm.city)}</dd>
            <dt>{t("Contact")}</dt><dd>Ananya Rao ({t("demo")})</dd>
          </dl></div>
        </Panel>
        <Panel title={`2 · ${t("Project and scheme")}`}>
          <div className="pb"><dl className="kv">
            <dt>{t("Product")}</dt><dd>{p.name}</dd><dt>{t("Category")}</dt><dd>{t(p.category)}</dd>
            <dt>{t("Scheme")}</dt><dd>{schemeName(t, p.scheme)}</dd><dt>{t("Sanction")}</dt><dd className="mono">{p.sanctionRef ?? "—"}</dd>
          </dl></div>
        </Panel>
        <Panel title={`3 · ${t("Trial plan")}`}>
          <div className="tw"><table><thead><tr><th>{t("Test")}</th><th>{t("Standard")}</th><th className="r">{t("Hours")}</th></tr></thead><tbody>
            {a.tests.map((x) => <tr key={x}><td>{testName(t, x)}</td><td className="mono">{test(x)?.standards.map((st) => t(st)).join(", ")}</td><td className="r mono">{test(x)?.hours}</td></tr>)}
          </tbody></table></div>
        </Panel>
        <Panel title={`4 · ${t("Charges and agreement")}`}>
          <div className="pb stack">
            {r.verdicts.map((v) => <div key={v.id} className="small"><b className="hl">{t(v.tTitle)}.</b> <span className="muted">{v.id === "capability" ? a.tests.map((x) => testName(t, x)).join(", ") : t(v.tDetail, P(v.params))}</span></div>)}
            <p className="notice">{t("Disputes are settled by conciliation as set out in the SOP of 7 Oct 2026.")} {t(r.rulesVersion)}.</p>
          </div>
        </Panel>
      </div>
      <Panel title={`5 · ${t("Documents")}`}>
        {r.docs.map((d) => <div className="li" key={d.key}><span className={`box ${a.docs[d.key] ? "y" : ""}`}>{a.docs[d.key] ? "✓" : ""}</span><span className="x">{t(d.label, d.params ? { scheme: t(String(d.params.scheme)) } : undefined)}</span><Tag tone={a.docs[d.key] ? "i" : "a"}>{a.docs[d.key] ? t("Attached") : t("Missing")}</Tag></div>)}
      </Panel>
      <p className="notice">{t("Generated by AstraTest Bharat on {date} · unclassified demo data.", { date: fmtDate(a.updatedAt) })}</p>
    </Shell>
  );
}
